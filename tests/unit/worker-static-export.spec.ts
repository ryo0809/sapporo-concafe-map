import {expect,test} from "@playwright/test";
import {existsSync,mkdirSync,mkdtempSync,readFileSync,rmSync,writeFileSync} from "node:fs";
import path from "node:path";
import {tmpdir} from "node:os";
import {prepareWorkerStatic} from "../../scripts/prepare-worker-static.mjs";
import {staticRoutes} from "../../worker/static-routes.mjs";

test("static export preserves exact generated bytes and never exports dynamic/private page data",()=>{
  const base=path.resolve(tmpdir()),root=mkdtempSync(path.join(base,"worker-static-test-"));
  try{
    const app=path.join(root,".next/server/app");mkdirSync(app,{recursive:true});
    for(const [route,config]of Object.entries(staticRoutes)){
      const file=path.join(app,config.source);mkdirSync(path.dirname(file),{recursive:true});
      writeFileSync(file,route==="/robots.txt"?"User-agent: *\nDisallow: /\n":`generated bytes ${route}`);
    }
    writeFileSync(path.join(app,"page.html"),"private dynamic map data");
    writeFileSync(path.join(app,"admin.html"),"private session data");
    prepareWorkerStatic(root);
    const output=path.join(root,".open-next/assets/_worker-static/noindex");
    for(const [route,config]of Object.entries(staticRoutes))expect(readFileSync(path.join(output,route==='/'?'index.html':route.slice(1)))).toEqual(readFileSync(path.join(app,config.source)));
    expect(existsSync(path.join(output,"page.html"))).toBe(false);
    expect(existsSync(path.join(output,"admin.html"))).toBe(false);
    expect(existsSync(path.join(root,".open-next/assets/_worker-static/indexable"))).toBe(false);
    writeFileSync(path.join(app,"robots.txt.body"),"User-agent: *\nAllow: /$\n");
    prepareWorkerStatic(root);
    expect(readFileSync(path.join(root,".open-next/assets/_worker-static/indexable/robots.txt"),"utf8")).toContain("Allow: /$");
    expect(readFileSync(path.join(root,".open-next/assets/_worker-static/indexable/index.html"),"utf8")).toContain("generated bytes /");
    expect(existsSync(path.join(root,".open-next/assets/_worker-static/indexable/admin.html"))).toBe(false);
  }finally{if(path.resolve(root).startsWith(base+path.sep))rmSync(root,{recursive:true,force:true});}
});
